-- ============================================================
-- Look Talk 웹 서비스
-- 사용자 이름 선택 입력 정책 반영
--
-- 변경 정책
-- 1. 환자/의료진 모두 회원가입 시
--    login_id + email + password를 입력한다.
--
-- 2. user_name은 회원가입 시 입력하지 않는다.
--    회원가입 이후 마이페이지에서 선택적으로 설정한다.
--
-- 3. 로그인은 환자/의료진 모두
--    login_id + password 방식으로 처리한다.
--
-- 4. 회원 사용자의 화면 표시 이름은 다음 규칙으로 처리한다.
--    - user_name 존재: user_name 표시
--    - user_name NULL: login_id 표시
--
-- 5. display_name 컬럼은 별도로 저장하지 않는다.
--    표시 이름은 API Response 생성 시 계산한다.
-- ============================================================


-- ============================================================
-- 1. USERS.USER_NAME 선택 입력으로 변경
-- ============================================================

-- 기존에는 회원가입 시 이름 입력을 전제로 user_name이 NOT NULL이었다.
-- 이름을 마이페이지에서 선택적으로 설정하도록 정책이 변경되었으므로
-- NOT NULL 제약을 제거한다.
ALTER TABLE users
    ALTER COLUMN user_name DROP NOT NULL;


-- ============================================================
-- 2. 기존 빈 문자열 데이터 정리
-- ============================================================

-- 개발 과정에서 빈 문자열('')이 이름으로 저장되어 있는 경우
-- 이름 미설정 상태와 동일하게 NULL로 정규화한다.
UPDATE users
SET user_name = NULL
WHERE user_name IS NOT NULL
  AND BTRIM(user_name) = '';


-- ============================================================
-- 3. 컬럼 설명 갱신
-- ============================================================

COMMENT ON COLUMN users.user_name IS
    '사용자가 마이페이지에서 선택적으로 설정하는 표시 이름. NULL인 경우 API에서는 login_id를 displayName으로 사용한다.';